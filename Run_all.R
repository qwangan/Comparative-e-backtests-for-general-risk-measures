# Run from the repository root. Existing forecast caches are reused.
local_library <- file.path(getwd(),".Rlib")
if(dir.exists(local_library)) .libPaths(c(local_library,.libPaths()))
source("Forecasts.R")
source("Analysis.R")
source("Iid_experiments.R")
source("tests_refined.R")
arguments <- commandArgs(trailingOnly=TRUE)
workers <- if(length(arguments)) as.integer(arguments[1]) else 4L
dir.create("results",showWarnings=FALSE)
run_traditional_iid()
run_comparative_iid()
for(dataset in c("stationary","nasdaq","structural_volatility","structural_shape")) {
  prepare_data(dataset)
  distributions <- if(dataset=="stationary") c("norm","std","sstd") else c("norm","sstd")
  for(distribution in distributions) prepare_forecasts(dataset,distribution,workers=workers)
  run_dataset(dataset)
  if(grepl("^structural",dataset)) run_structural_assessments(dataset)
}
source("Publication_figures.R")
make_publication_figures()
source("Write_tables.R")
write_numerical_tables()
source("Calibration_diagnostics.R")
run_calibration_diagnostics()
source("Simulation_truth.R")
run_simulation_truth()
run_betting_diagnostics()
writeLines(trimws(capture.output(sessionInfo()),which="right"),"results/session-info.txt")
saveRDS(numeric_config,"results/run-config.rds")
source("Validate_results.R")
validate_results()
cat("All experiments completed. Tables are in results/ and figures in figures/.\n")
